// ¿El número sirve para ese prefijo? Devuelve el error o ''.
// Colombia: celular de 10 dígitos que empieza por 3.
// Otros países: entre 6 y 14 dígitos (máximo 15 contando el prefijo).
export function validarCelular(prefijo, numero) {
    if (!numero) {
        return '';
    }
    if (prefijo === '+57') {
        return /^3\d{9}$/.test(numero)
            ? ''
            : t("El celular de Colombia debe tener 10 d\u00EDgitos y empezar por 3.");
    }
    const total = prefijo.replace('+', '').length + numero.length;
    if (numero.length < 6 || total > 15) {
        return t("Revisa el n\u00FAmero de celular: es muy corto o muy largo para ese pa\u00EDs.");
    }
    return '';
}
